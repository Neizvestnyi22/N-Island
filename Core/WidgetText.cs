        /// <summary>Translate only known template literals. Never translate user state, selectors or commands.</summary>
        public static string Localize(string html, Func<string,string> translate)
        {
            foreach (var key in Keys)
            {
                var value = translate(key);
                if (value == key) continue;
                html = html.Replace("'" + key + "'", JsonSerializer.Serialize(value, new JsonSerializerOptions { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }));
                html = html.Replace(">" + key + "<", ">" + WebUtility.HtmlEncode(value) + "<");
            }
            return html;
        }
